#include <stdio.h>                      /* 【规定】要用 printf 就得有这行 */

int main(void)                          /* 【规定】程序入口，照抄 */
{
    char s[] = "ABC";                   /* 【举例】内容 "ABC" 是我给你挑的，你可以换 */

    printf("s[0] = %c , %d\n", s[0], s[0]);   /* 【举例】打印第 0 格 */
    printf("s[1] = %c , %d\n", s[1], s[1]);   /* 【举例】打印第 1 格 */
    printf("s[2] = %c , %d\n", s[2], s[2]);   /* 【举例】打印第 2 格 */
    printf("s[3] = %c , %d\n", s[3], s[3]);   /* 【举例】打印第 3 格（这一格很关键） */

    return 0;                           /* 【规定】照抄 */
}
